// UNLOCK service worker — Web Push only (no offline caching yet).
// Requires NEXT_PUBLIC_VAPID_PUBLIC_KEY / VAPID_PRIVATE_KEY to be set and a
// send path wired up server-side (e.g. a `web-push` call on reward unlock).

self.addEventListener("push", (event) => {
  if (!event.data) return;
  let payload;
  try {
    payload = event.data.json();
  } catch {
    payload = { title: "UNLOCK", body: event.data.text() };
  }

  const title = payload.title || "UNLOCK";
  const options = {
    body: payload.body || "",
    icon: "/icon-192.png",
    badge: "/icon-192.png",
    data: { url: payload.url || "/discover" },
    tag: payload.tag
  };

  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = event.notification.data?.url || "/discover";
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if (client.url.includes(url) && "focus" in client) return client.focus();
      }
      if (self.clients.openWindow) return self.clients.openWindow(url);
    })
  );
});
